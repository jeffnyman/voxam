    /// <summary>The eight row bytes of a §16 character, or null for a code the font does not draw.</summary>
    public static byte[]? Bitmap(string character) =>
        character.Length == 1 && Bitmaps.TryGetValue(character[0], out var rows) ? rows : null;

    /// <summary>Whether one pixel of a bitmap is lit.</summary>
    public static bool Lit(byte[] bitmap, int x, int y) => (bitmap[y] & (0x80 >> x)) != 0;
